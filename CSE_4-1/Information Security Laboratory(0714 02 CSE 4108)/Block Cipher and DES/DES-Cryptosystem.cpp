void print(string description, string matrix[], int rows)
{
    cout << description << endl;
    for (int i = 0; i < rows; i++)
    {
        for (auto ch : matrix[i])
            cout << ch << " ";
        cout << endl;
    }
    cout << endl;
}
void des_cryptosystem(string &plaintext, string &key)
{
    string L0 = plaintext.substr(0, 32), R0 = plaintext.substr(32, 32), K = key.substr(0, 48);
    string S_[8], ER0[8], K0[8], SB[8], PS[4], R1, L1 = R0, L0_[4], R1_[4];
    int i, j, k;
    cout << "L0: " << L0 << "\nR0: " << R0 << endl;
    for (i = 0; i < 8; i++)
    {
        for (int j = 0; j < 6; j++)
        {
            ER0[i] += R0[EP[i][j]], K0[i] += K[6 * i + j];
            S_[i].push_back((char)(((R0[EP[i][j]] - '0') ^ (K[6 * i + j] - '0')) + '0'));
        }
        int j = stoi(string{S_[i][0], S_[i][5]}, nullptr, 2), k = stoi(string{S_[i][1], S_[i][2], S_[i][3], S_[i][4]}, nullptr, 2);
        SB[i] = bitset<4>(S[i][j][k]).to_string();
    }
    print("Expanded R0:", ER0, 8), print("K:", K0, 8);
    print("XOR of Expanded R0 and K:", S_, 8), print("S Box:", SB, 8);
    for (i = 0; i < 4; i++)
    {
        for (j = 0; j < 8; j++)
        {
            PS[i].push_back(SB[(P[i][j] / 4)][(P[i][j] % 4)]), L0_[i].push_back(L0[i * 8 + j]);
            R1_[i].push_back((char)((((L0[i * 8 + j] - '0') ^ (PS[i][j] - '0'))) + '0'));
            R1.push_back((char)((((L0[i * 8 + j] - '0') ^ (PS[i][j] - '0'))) + '0'));
        }
    }
    print("Permutation of S Box: ", PS, 4), print("L0: ", L0_, 4);
    print("R1 = XOR of L0 and Permutation of S Box:", R1_, 4);
    cout << "L1: " << L1 << "\nR1: " << R1 << "\nC1: " << R1 + L1 << endl;
}
